def _to_salary_real(s60: str) -> str:
    """把 '1.5-2.5万' / '8000-12000元' / '150-300元' 转成智联的 salaryReal 数字串。"""
    m = re.search(r"(\d+(?:\.\d+)?)\s*[-~]\s*(\d+(?:\.\d+)?)", s60)
    if not m:
        return ""
    lo, hi = float(m.group(1)), float(m.group(2))
    if "万" in s60:
        lo, hi = lo * 10000, hi * 10000
    return f"{int(lo)}-{int(hi)}"


def generate(count: int = 600, seed: int = 20261025):
    """生成 count 条演示岗位（已分类、已算好薪资档位）。"""
    rng = random.Random(seed)
    records = []
    idx = 0
    base_time = datetime.now()

    while len(records) < count:
        title, skills, s60, exp, degree, industry, ctype, scale = TEMPLATES[idx % len(TEMPLATES)]
        idx += 1
        city, code = rng.choices(CITIES, weights=CITY_WEIGHT, k=1)[0]
        district = rng.choice(DISTRICTS[city])
        company = rng.choice(COMPANIES)
        no = f"CCL{code}{len(records) + 1:06d}J{100000 + len(records)}"

        item = {
            "name": title,
            "salary60": s60,
            "salaryReal": _to_salary_real(s60),
            "workingExp": exp,
            "education": degree,
            "companyName": company,
            "companySize": scale,
            "industryName": industry,
            "propertyName": ctype,
            "workCity": city,
            "cityDistrict": district,
            "streetName": rng.choice(["", "科技园", "CBD", "高新区"]),
            "publishTime": (base_time - timedelta(hours=rng.randint(1, 240)))
            .strftime("%Y-%m-%d %H:%M:%S"),
            "jobSkillTags": [{"id": 0, "name": s, "standard": False} for s in skills.split("/")],
            "welfareLabel": rng.sample(["五险一金", "年终奖", "带薪年假", "补充医疗", "餐补", "双休"],
                                       k=rng.randint(2, 4)),
            "number": no,
            "positionUrl": DETAIL_URL.format(no),
            "is_demo": True,
        }
        rec = parse_position(item, keyword=title[:2], source_city=city)
        records.append(enrich(rec))

    rng.shuffle(records)
    return records
