def _text_of(record: dict) -> str:
    parts = [
        record.get("job_name", ""),
        " ".join(record.get("skills") or []),
        " ".join(record.get("welfare") or []),
    ]
    return clean(" ".join(parts)).lower()


def _match_title(title: str):
    # 去掉空格：智联常见「UI 设计师」「AI 视频识别」这种带空格的写法
    t = re.sub(r"\s+", "", clean(title)).lower()
    if not t:
        return None
    for l1, l2, keywords in CATEGORY_RULES:
        for kw in keywords:
            if kw.lower() in t:
                return l1, l2
    return None


def _match_by_skills(record: dict):
    skills = " ".join(record.get("skills") or []).lower()
    if not skills:
        return None
    for l1, words in SKILL_HINTS.items():
        for w in words:
            if w in skills:
                # 一级分类命中后，尽量找一条同级的二级规则
                for rl1, rl2, kws in CATEGORY_RULES:
                    if rl1 == l1 and any(k.lower() in skills for k in kws):
                        return rl1, rl2
                return l1, "其他"
    return None


def classify(record: dict):
    """返回 (一级分类, 二级分类)。先看岗位名称，再看技能标签，都没有就归入「其他」。"""
    hit = _match_title(record.get("job_name", ""))
    if hit:
        return hit
    hit = _match_by_skills(record)
    if hit:
        return hit
    return FALLBACK


def enrich(record: dict) -> dict:
    """给一条岗位补全所有派生字段（分类、薪资、经验/学历档位、是否实习）。"""
    l1, l2 = classify(record)
    record["category_l1"] = l1
    record["category_l2"] = l2
    record["exp_level"] = experience_level(record.get("experience", ""))
    record["degree_level"] = degree_level(record.get("degree", ""))
    record["is_intern"] = "是" if ("实习" in clean(record.get("job_name", "")) or
                                   "实习" in clean(record.get("experience", ""))) else "否"
    record["is_demo"] = record.get("is_demo", False)
    return record
